const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const { io } = require('../frontend/node_modules/socket.io-client');

test('Kinonames uses real room identity, private snapshots, consent, reconnect, restart and isolated settings', { timeout: 18000 }, async () => {
  const child = spawn(process.execPath, ['backend/server.js'], { env: { ...process.env, PORT: '3198', ROOM_STATE_FILE: '' }, stdio: ['ignore', 'pipe', 'pipe'] });
  const clients = [];
  const call = (s, event, data) => s.timeout(2500).emitWithAck(event, data);
  const connect = () => new Promise((resolve, reject) => {
    const s = io('http://localhost:3198', { reconnection: false }); clients.push(s);
    s.once('connect', () => resolve(s)); s.once('connect_error', reject);
  });
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  try {
    await new Promise((resolve, reject) => {
      child.stdout.on('data', b => { if (String(b).includes('Backend server running')) resolve(); });
      child.once('exit', () => reject(Error('Test server exited')));
    });
    const host = await connect(), guess = await connect();
    const { lobbyId } = await call(host, 'create_lobby', { targetVP: 12 });
    const h = await call(host, 'join_lobby', { lobbyId, nickname: 'Ведущий' });
    const g = await call(guess, 'join_lobby', { lobbyId, nickname: 'Угадываю' });
    let hv, gv;
    host.on('lobby_update', v => { hv = v; }); guess.on('lobby_update', v => { gv = v; });
    assert.equal((await call(host, 'update_target_vp', { lobbyId, mode: 'original', targetVP: 12, categories: ['films'], hiddenMode: true, repeatRatings: true })).success, true);
    assert.equal((await call(host, 'update_target_vp', { lobbyId, mode: 'kinonames' })).success, true);
    assert.equal((await call(guess, 'kinonames_settings', { lobbyId, settings: { coop: { lives: 5 } } })).success, false);
    assert.equal((await call(host, 'kinonames_settings', { lobbyId, settings: { coop: { blue: 1, black: 0, clues: 1, lives: 2 } } })).success, true);
    assert.equal((await call(host, 'kinonames_assign', { lobbyId, team: 'blue', leader: true })).success, true);
    assert.equal((await call(guess, 'kinonames_assign', { lobbyId, team: 'blue', leader: true })).success, false);
    assert.equal((await call(guess, 'kinonames_assign', { lobbyId, team: 'blue', leader: false })).success, true);
    assert.equal((await call(host, 'update_target_vp', { lobbyId, mode: 'original', targetVP: 999, categories: ['superheroes'], hiddenMode: false })).success, true);
    await wait(30);
    assert.equal(hv.mode,'original');assert.equal(hv.targetVP,12);assert.deepEqual(hv.categories,['films']);assert.equal(hv.hiddenMode,true);assert.equal(hv.repeatRatings,true);
    assert.equal((await call(host, 'update_target_vp', { lobbyId, mode:'kinonames' })).success,true);
    const launched = await call(host, 'launch_game', lobbyId);
    assert.equal(launched.success, true, launched.message);
    await wait(40);
    assert.equal(gv.state, 'kinonames');
    assert.equal(gv.categories[0], 'superheroes');
    assert.equal(hv.kinonames.game.board.filter(c => c.color).length, 25);
    assert.equal(gv.kinonames.game.board.filter(c => c.color).length, 0);
    assert.equal(JSON.stringify(gv).includes('sessionToken'), false);
    const late=await connect();let lv;
    late.on('lobby_update',v=>{lv=v;});
    const joinedLate=await call(late,'join_lobby',{lobbyId,nickname:'Ждём'});
    assert.equal(joinedLate.success,true);assert.equal(joinedLate.lobby.waitingRoom,true);
    assert.equal(joinedLate.lobby.state,'waiting');assert.equal(joinedLate.lobby.kinonames,undefined);
    assert.equal(joinedLate.lobby.movies,undefined);assert.equal(hv.players.length,2);
    assert.equal((await call(late,'kinonames_assign',{lobbyId,team:'blue',leader:false})).success,false);
    assert.equal((await call(late,'kinonames_action',{lobbyId,action:{type:'ready'}})).success,false);
    const action = (v, data) => ({ lobbyId, action: { gameId: v.kinonames.game.gameId, turnId: v.kinonames.game.turnId, ...data } });
    assert.equal((await call(host, 'kinonames_action', action(hv, { type: 'clue', word: 'Сила', count: 1 }))).success, true);
    await wait(30);
    const blue = hv.kinonames.game.board.find(c => c.color === 'blue');
    assert.equal((await call(host, 'kinonames_action', action(hv, { type: 'vote', cardId: blue.id }))).success, false);
    assert.equal((await call(guess, 'submit_rating', { lobbyId, movieId: blue.id, rating: 'S' })).success, false);
    const packet = action(gv, { type: 'vote', cardId: blue.id });
    assert.equal((await call(guess, 'kinonames_action', packet)).success, true);
    await wait(50);
    assert.equal(gv.kinonames.game.board.some(c => c.revealed), false);
    const replacement = await connect();
    const restored = await call(replacement, 'join_lobby', { lobbyId, sessionToken: g.player.sessionToken });
    assert.equal(restored.player.id, g.player.id);
    assert.deepEqual(restored.lobby.kinonames.game.board.map(c => c.id), gv.kinonames.game.board.map(c => c.id));
    replacement.on('lobby_update', v => { gv = v; });
    assert.equal((await call(guess, 'kinonames_action', packet)).success, false, 'replaced transport cannot vote');
    await wait(3200);
    assert.equal(gv.state, 'game_over');
    assert.equal(gv.kinonames.game.result.winner, 'blue');
    assert.equal((await call(replacement, 'kinonames_action', packet)).success, false);
    assert.equal((await call(host, 'restart_game', lobbyId)).success, true);
    await wait(30);
    assert.equal(hv.state, 'kinonames'); assert.equal(hv.kinonames.game.phase, 'ready');
    assert.equal(hv.players.length,3);assert.equal(lv.waitingRoom,undefined);
    assert.equal(hv.kinonames.game.board.some(c=>c.color||c.name),false);
    assert.equal(hv.kinonames.settings.coop.clues, 1);
    assert.equal((await call(host,'kinonames_action',action(hv,{type:'ready'}))).success,true);
    assert.equal((await call(replacement,'kinonames_action',action(gv,{type:'ready'}))).success,true);
    assert.equal((await call(late,'kinonames_action',action(lv,{type:'ready'}))).success,true);
    await wait(30);assert.equal(hv.kinonames.game.phase,'clue');
  } finally { clients.forEach(s => s.close()); child.kill(); }
});
